<script setup lang="ts">
import { formatDistanceToNow } from "date-fns";
import type { AuthCredentials } from "~/types";
import { useBillingStore } from "~/stores/billing";

const props = defineProps<{
  accountSid: string;
  authCredentials: AuthCredentials;
  accountName?: string;
  isSubaccount?: boolean;
  parentAccountSid?: string;
  parentAccountName?: string;
}>();

const emit = defineEmits<{
  (e: "refresh-all" | "refresh-balance"): void;
}>();

const billingStore = useBillingStore();

const balanceLastRefreshedText = computed(() => {
  if (!billingStore.balanceLastFetchedAt) {
    return "";
  }
  try {
    return formatDistanceToNow(new Date(billingStore.balanceLastFetchedAt), { addSuffix: true });
  } catch {
    return "";
  }
});
</script>

<template>
  <div class="space-y-6">
    <!-- Top Back Navigation & Title -->
    <div class="flex flex-col md:flex-row md:items-center justify-between gap-4">
      <div class="space-y-1">
        <div class="flex items-center gap-2">
          <NuxtLink
            :to="`/accounts/${props.accountSid}`"
            class="inline-flex items-center gap-1.5 text-xs text-neutral-500 hover:text-neutral-900 dark:text-neutral-400 dark:hover:text-white transition-colors group">
            <UIcon name="i-lucide-arrow-left" class="size-3.5 transition-transform group-hover:-translate-x-0.5" />
            <span>Account Dashboard</span>
          </NuxtLink>
          <span class="text-neutral-300 dark:text-neutral-700">/</span>
          <span class="text-xs font-medium text-neutral-700 dark:text-neutral-300">Billing & Usage</span>
        </div>

        <div class="flex items-center gap-3 pt-1">
          <div class="size-10 rounded-xl bg-emerald-50 dark:bg-emerald-950/60 text-emerald-600 dark:text-emerald-400 flex items-center justify-center shrink-0 ring-1 ring-emerald-500/20">
            <UIcon name="i-lucide-receipt" class="size-5" />
          </div>
          <div>
            <div class="flex items-center gap-2.5">
              <h1 class="text-xl sm:text-2xl font-bold text-neutral-900 dark:text-white">
                Billing & Usage
              </h1>
              <UBadge
                v-if="props.isSubaccount"
                color="warning"
                variant="subtle"
                size="sm">
                Subaccount
              </UBadge>
              <UBadge
                v-else
                color="success"
                variant="subtle"
                size="sm">
                Primary Account
              </UBadge>
            </div>
            <p class="text-xs sm:text-sm text-neutral-500 dark:text-neutral-400 mt-0.5 font-mono">
              {{ props.accountName || "Account" }} &bull; {{ props.accountSid }}
            </p>
          </div>
        </div>
      </div>

      <!-- Action Buttons -->
      <div class="flex flex-wrap items-center gap-2.5 self-start md:self-center">
        <UButton
          color="neutral"
          variant="outline"
          size="sm"
          :loading="billingStore.isLoadingUsage"
          title="Refresh usage records from Twilio"
          @click="emit('refresh-all')">
          <template #leading>
            <UIcon name="i-lucide-refresh-cw" class="size-4" :class="{ 'animate-spin': billingStore.isLoadingUsage }" />
          </template>
          Refresh Data
        </UButton>

        <UButton
          v-if="billingStore.enrichedRecords.length > 0"
          color="neutral"
          variant="subtle"
          size="sm"
          title="Export current usage records to CSV"
          @click="billingStore.exportToCsv">
          <template #leading>
            <UIcon name="i-lucide-download" class="size-4" />
          </template>
          Export CSV
        </UButton>
      </div>
    </div>

    <!-- Subaccount Parent Notice Banner (if viewing subaccount) -->
    <div
      v-if="props.isSubaccount && props.parentAccountSid"
      class="p-4 rounded-xl bg-amber-500/10 border border-amber-500/20 flex flex-col sm:flex-row sm:items-center justify-between gap-3 text-xs">
      <div class="flex items-center gap-3">
        <div class="size-8 rounded-lg bg-amber-500/20 text-amber-600 dark:text-amber-400 flex items-center justify-center shrink-0">
          <UIcon name="i-lucide-info" class="size-4" />
        </div>
        <div>
          <span class="font-semibold text-neutral-900 dark:text-white">
            Subaccount of {{ props.parentAccountName || props.parentAccountSid }}
          </span>
          <p class="text-neutral-500 dark:text-neutral-400 mt-0.5">
            Usage charges generated by this subaccount are billed to the parent master account. Primary account balance applies.
          </p>
        </div>
      </div>
      <NuxtLink
        :to="`/accounts/${props.parentAccountSid}/billing-usage`"
        class="text-amber-600 dark:text-amber-400 hover:underline font-medium shrink-0 flex items-center gap-1">
        <span>View Parent Billing</span>
        <UIcon name="i-lucide-arrow-right" class="size-3.5" />
      </NuxtLink>
    </div>

    <!-- Stats Cards Grid -->
    <div class="grid grid-cols-1 sm:grid-cols-2 lg:grid-cols-4 gap-4">
      <!-- 1. Total Period Cost -->
      <UCard class="ring-1 ring-neutral-200 dark:ring-neutral-800 shadow-sm relative overflow-hidden">
        <div class="space-y-2">
          <div class="flex items-center justify-between">
            <span class="text-xs font-medium text-neutral-500 dark:text-neutral-400 flex items-center gap-1.5">
              <UIcon name="i-lucide-badge-dollar-sign" class="size-3.5 text-blue-500" />
              Total Period Cost
            </span>
            <UBadge color="info" variant="subtle" size="xs">
              Selected Period
            </UBadge>
          </div>

          <div class="space-y-0.5">
            <div class="text-2xl font-bold tracking-tight text-neutral-900 dark:text-white">
              {{ billingStore.formatPrice(billingStore.totalSpend, billingStore.currencyCode) }}
            </div>
            <p class="text-xs text-neutral-400">
              {{ billingStore.fromDate || "Start" }} &rarr; {{ billingStore.toDate || "Today" }}
            </p>
          </div>
        </div>
      </UCard>

      <!-- 2. Live Account Balance -->
      <UCard class="ring-1 ring-neutral-200 dark:ring-neutral-800 shadow-sm relative overflow-hidden">
        <div class="space-y-2">
          <div class="flex items-center justify-between">
            <span class="text-xs font-medium text-neutral-500 dark:text-neutral-400 flex items-center gap-1.5">
              <UIcon name="i-lucide-wallet" class="size-3.5 text-emerald-500" />
              Account Balance
            </span>
            <UButton
              v-if="!billingStore.isSubaccountBalanceUnavailable"
              color="neutral"
              variant="ghost"
              size="xs"
              :loading="billingStore.isLoadingBalance"
              title="Refresh live balance"
              aria-label="Refresh balance"
              class="size-6 p-0"
              @click="emit('refresh-balance')">
              <UIcon name="i-lucide-refresh-cw" class="size-3 text-neutral-400 hover:text-neutral-700 dark:hover:text-neutral-200" :class="{ 'animate-spin': billingStore.isLoadingBalance }" />
            </UButton>
          </div>

          <div v-if="billingStore.isSubaccountBalanceUnavailable" class="pt-1">
            <UBadge color="neutral" variant="subtle" size="sm" class="text-xs">
              Shared Parent Balance
            </UBadge>
            <p class="text-xs text-neutral-500 dark:text-neutral-400 mt-1">
              Subaccounts draw from master balance.
            </p>
          </div>
          <div v-else-if="billingStore.balanceError" class="pt-1">
            <span class="text-xs text-red-500 flex items-center gap-1">
              <UIcon name="i-lucide-alert-circle" class="size-3.5 shrink-0" />
              Failed to load balance
            </span>
          </div>
          <div v-else class="space-y-0.5">
            <div class="text-2xl font-bold tracking-tight text-neutral-900 dark:text-white flex items-baseline gap-1.5">
              <span>{{ billingStore.formatPrice(billingStore.balance?.balance, billingStore.balance?.currency) }}</span>
            </div>
            <p class="text-xs text-neutral-400">
              {{ balanceLastRefreshedText ? `Updated ${balanceLastRefreshedText}` : "Live from Twilio API" }}
            </p>
          </div>
        </div>
      </UCard>

      <!-- 3. Active Categories -->
      <UCard class="ring-1 ring-neutral-200 dark:ring-neutral-800 shadow-sm relative overflow-hidden">
        <div class="space-y-2">
          <div class="flex items-center justify-between">
            <span class="text-xs font-medium text-neutral-500 dark:text-neutral-400 flex items-center gap-1.5">
              <UIcon name="i-lucide-layers" class="size-3.5 text-purple-500" />
              Active Categories
            </span>
            <UBadge color="neutral" variant="subtle" size="xs">
              {{ billingStore.groupedUsage.length }} Groups
            </UBadge>
          </div>

          <div class="space-y-0.5">
            <div class="text-2xl font-bold tracking-tight text-neutral-900 dark:text-white">
              {{ billingStore.activeCategoriesCount }}
            </div>
            <p v-if="billingStore.highestSpendGroup" class="text-xs text-neutral-400 truncate" :title="`${billingStore.highestSpendGroup.group}: ${billingStore.formatPrice(billingStore.highestSpendGroup.amount)}`">
              Top: <span class="font-medium text-neutral-700 dark:text-neutral-300">{{ billingStore.highestSpendGroup.group }}</span>
            </p>
            <p v-else class="text-xs text-neutral-400">
              Billable service categories
            </p>
          </div>
        </div>
      </UCard>

      <!-- 4. Query Scope -->
      <UCard class="ring-1 ring-neutral-200 dark:ring-neutral-800 shadow-sm relative overflow-hidden">
        <div class="space-y-2">
          <div class="flex items-center justify-between">
            <span class="text-xs font-medium text-neutral-500 dark:text-neutral-400 flex items-center gap-1.5">
              <UIcon name="i-lucide-calendar-range" class="size-3.5 text-amber-500" />
              Subaccounts Scope
            </span>
            <UBadge
              :color="billingStore.includeSubaccounts ? 'success' : 'neutral'"
              variant="subtle"
              size="xs">
              {{ billingStore.includeSubaccounts ? "Included" : "Excluded" }}
            </UBadge>
          </div>

          <div class="space-y-0.5">
            <div class="text-base font-semibold text-neutral-900 dark:text-white truncate">
              {{ billingStore.includeSubaccounts ? "Includes Subaccounts" : "Primary Only" }}
            </div>
            <p class="text-xs text-neutral-400 truncate">
              {{ billingStore.filteredGroups.reduce((acc, g) => acc + g.children.length, 0) }} matching line items
            </p>
          </div>
        </div>
      </UCard>
    </div>
  </div>
</template>
